def section_max_words(report_type: str, title: str) -> int:
    limits = SECTION_MAX_WORDS.get(report_type) or {}
    if title in limits:
        return limits[title]
    original = _original_catalog_title(report_type, title)
    if original in limits:
        return limits[original]
    return FREE_SECTION_MAX_WORDS if report_type.endswith("_free") else 260


def _is_free_report(report_type: str) -> bool:
    return report_type.endswith("_free")


def _section_volume_line(report_type: str, title: str) -> str:
    maximum = section_max_words(report_type, title)
    if _is_free_report(report_type):
        return f"{FREE_SECTION_MIN_WORDS}–{maximum} слов."
    return f"Максимум {maximum} слов."

