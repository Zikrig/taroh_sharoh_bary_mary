def _normalize_prompt_title(value: str) -> str:
    text = value.strip()
    text = re.sub(r"^раздел\s*\d+\s*[:.\-–)]*\s*", "", text, flags=re.IGNORECASE)
    text = re.sub(r"^\d{1,2}[.)]\s*", "", text)
    text = re.sub(r"\s+", " ", text).strip(" .:")
    return text.casefold()


def _split_product_blocks(prompt: str) -> tuple[str, list[tuple[str, str]]]:
    chunks = [part.strip() for part in _HEADER_SPLIT.split(prompt) if part.strip()]
    if not chunks:
        return prompt.strip(), []
    intro = chunks[0]
    blocks: list[tuple[str, str]] = []
    index = 1
    while index < len(chunks) - 1:
        blocks.append((chunks[index], chunks[index + 1]))
        index += 2
    return intro, blocks


def _header_matches(header: str, wanted: dict[str, str]) -> str | None:
    lines = [line.strip() for line in header.splitlines() if line.strip()]
    for candidate in (*lines, " ".join(lines)):
        matched = wanted.get(_normalize_prompt_title(candidate))
        if matched:
            return matched
    return None


def product_prompt_for_titles(report_type: str, titles: list[str]) -> str:
    """Keep the product intro and only the requested section instructions."""
    full = assembled_product_prompt(report_type)
    if not titles:
        return full
    intro, blocks = product_prompt_parts(report_type)
    wanted = {_normalize_prompt_title(title): title for title in titles}
    selected: dict[str, str] = {}
    for header, body in blocks:
        matched = _header_matches(header, wanted)
        if not matched or matched in selected:
            continue
        volume = _section_volume_line(report_type, matched)
        note = (
            " Не короче минимума и не длиннее потолка."
            if _is_free_report(report_type)
            else " Это потолок, не цель."
        )
        selected[matched] = "\n".join(
            [
                "==================================================",
                header,
                "==================================================",
                body,
                volume + note,
            ]
        )
    if len(titles) == 1:
        only = (
            f"Сейчас напиши ТОЛЬКО раздел «{titles[0]}». Остальные разделы этого продукта не пиши.\n"
            "Не переноси общий объём всего отчёта на этот раздел: он ограничен своим лимитом слов."
        )
    else:
        only = (
            "Сейчас напиши ТОЛЬКО эти разделы. Остальные разделы этого продукта не пиши.\n"
            "Не переноси общий объём всего отчёта на эту пачку: каждый раздел ограничен своим лимитом слов."
        )
    if len(selected) != len(titles):
        return "\n\n".join([full, only])
    ordered = [selected[title] for title in titles]
    return "\n\n".join([intro, only, *ordered])


def section_title_batches(titles: list[str], size: int = PAID_SECTION_BATCH) -> list[list[str]]:
    return [titles[index:index + size] for index in range(0, len(titles), size)]


def output_format_block(
    titles: list[str],
    *,
    report_type: str | None = None,
    batch: bool = False,
) -> str:
    listed = "\n".join(f"- {title}" for title in titles)
    example = titles[0] if titles else "Название раздела"
    if len(titles) == 1:
        scope = "Верни только этот раздел одним сообщением."
    elif batch:
        scope = "Верни только эти разделы одним сообщением."
    else:
        scope = "Верни весь разбор одним сообщением."
    limits = ""
    if report_type and titles:
        rows = "\n".join(
            f"- {title}: {_section_volume_line(report_type, title).rstrip('.')}"
            for title in titles
        )
        if _is_free_report(report_type):
            limits = f"""
Объём каждого текущего раздела: {FREE_SECTION_MIN_WORDS}–{FREE_SECTION_MAX_WORDS} слов.
{rows}

Не короче {FREE_SECTION_MIN_WORDS} и не длиннее {FREE_SECTION_MAX_WORDS} слов.
"""
        else:
            limits = f"""
Лимит слов для текущих разделов:
{rows}

Не превышай лимит. Если раздел можно сказать короче без потери точности — скажи короче.
"""
    return _render_pipeline(
        "format",
        scope=scope,
        delimiter=SECTION_DELIMITER,
        example=example,
        listed=listed,
        limits=limits,
    ).strip()


def format_delimited_sections(sections: list[dict[str, str]]) -> str:
    parts: list[str] = []
    for item in sections:
        title = str(item.get("title") or "").strip()
        content = str(item.get("content") or "").strip()
        if not title or not content:
            continue
        parts.extend([SECTION_DELIMITER, title, SECTION_DELIMITER, content, ""])
    return "\n".join(parts).strip()


def build_concept_prompt(
    report_type: str,
    natal_text: str,
    titles: list[str],
    prior_sections: list[dict[str, str]] | None = None,
) -> str:
    listed = "\n".join(f"- {title}" for title in titles)
    prior = ""
    if prior_sections:
        chunks = [
            f"--- {item.get('title')} ---\n{item.get('content')}"
            for item in prior_sections
            if item.get("title") and item.get("content")
        ]
        if chunks:
            prior = (
                "\n\nУже показанный бесплатный мини-разбор — учти как смысловую основу, "
                "не копируй:\n" + "\n\n".join(chunks)
            )
    instruction = _render_pipeline(
        "concept",
        report_type=report_type,
        listed=listed,
        prior=prior,
    )
    return f"""
{natal_text}

{instruction}

{SECTION_DELIMITER}
{CONCEPT_TITLE}
{SECTION_DELIMITER}

текст задумки без заголовка внутри.

Не пиши преамбулу до разделителя. Без Markdown и **.
""".strip()


