def build_career_hints(
    chart: dict[str, Any], *, include_houses: bool = True
) -> dict[str, Any]:
    """Return only chart-relevant career suggestions for the model."""
    planet_houses = Counter(
        position["house"] for position in chart["planets"].values()
    )
    active_houses = [
        {
            "house": house,
            "themes": HOUSE_THEMES[house],
            "profession_examples": HOUSE_PROFESSIONS[house],
        }
        for house, _ in planet_houses.most_common(3)
    ] if include_houses else []
    planet_hints = [
        {
            "planet": planet,
            "sign": position["sign"],
            "talent_examples": PLANET_TALENTS[planet],
            "work_style": SIGN_WORK_STYLES[position["sign"]],
        }
        for planet, position in chart["planets"].items()
        if planet in PLANET_TALENTS
    ]
    return {
        "important": (
            "Подсказки — это варианты для сопоставления с картой, а не готовый "
            "вердикт о профессии. Выбирай только варианты, подтверждённые несколькими фактами."
        ),
        "active_house_professions": active_houses,
        "planet_talent_hints": planet_hints,
    }
